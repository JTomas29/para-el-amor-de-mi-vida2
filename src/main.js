function initCitasCarousels() {
  document.querySelectorAll('[data-cita-carousel]').forEach((carousel) => {
    const citaIndex = Number(carousel.dataset.citaCarousel)
    const cita = citas[citaIndex]
    if (!cita || cita.fotos.length < 2) return

    let photoIndex = 0
    const image = carousel.querySelector('.cita-photo')
    const counter = carousel.querySelector('[data-cita-count]')
    const showPhoto = (nextIndex) => {
      photoIndex = (nextIndex + cita.fotos.length) % cita.fotos.length
      image.src = cita.fotos[photoIndex]
      image.alt = `${cita.titulo} - foto ${photoIndex + 1}`
      image.dataset.fotosIndice = photoIndex
      counter.textContent = `${photoIndex + 1} / ${cita.fotos.length}`
    }

    carousel.querySelector('[data-cita-prev]').addEventListener('click', () => showPhoto(photoIndex - 1))
    carousel.querySelector('[data-cita-next]').addEventListener('click', () => showPhoto(photoIndex + 1))
  })
}

function initFotosJuntos() {
  const root = document.querySelector('[data-fotos-juntos]')
  const dots = root.querySelector('[data-fotos-juntos-dots]')
  dots.innerHTML = fotosJuntos.map((_, index) => `
    <button type="button" class="fotos-juntos-dot h-2.5 w-2.5 rounded-full transition-colors focus:outline-none focus-visible:ring-2 focus-visible:ring-mint" data-fotos-juntos-foto="${index}" aria-label="Foto ${index + 1}"></button>
  `).join('')

  const imgWrap = root.querySelector('.fotos-juntos-img-wrap')
  let startX = null
  let startY = null
  imgWrap.addEventListener('pointerdown', (event) => {
    startX = event.clientX
    startY = event.clientY
  })
  imgWrap.addEventListener('pointerup', (event) => {
    if (startX === null) return
    const dx = event.clientX - startX
    const dy = event.clientY - startY
    startX = null
    startY = null
    if (Math.abs(dx) > 48 && Math.abs(dx) > Math.abs(dy)) {
      showFotosJuntos(fotosJuntosIndice + (dx < 0 ? 1 : -1))
    }
  })

  root.querySelector('[data-fotos-juntos-prev]').addEventListener('click', () => showFotosJuntos(fotosJuntosIndice - 1))
  root.querySelector('[data-fotos-juntos-next]').addEventListener('click', () => showFotosJuntos(fotosJuntosIndice + 1))
  dots.querySelectorAll('.fotos-juntos-dot').forEach((dot) => {
    dot.addEventListener('click', () => showFotosJuntos(Number(dot.dataset.fotosJuntosFoto)))
  })
  showFotosJuntos(0)
}

function showFotosJuntos(photoIndex) {
  const root = document.querySelector('[data-fotos-juntos]')
  fotosJuntosIndice = ((photoIndex % fotosJuntos.length) + fotosJuntos.length) % fotosJuntos.length
  const imgWrap = root.querySelector('.fotos-juntos-img-wrap')
  imgWrap.innerHTML = ''

  const img = document.createElement('img')
  img.className = 'carrusel-foto h-full w-full object-contain'
  img.alt = `Nosotros dos - foto ${fotosJuntosIndice + 1}`
  img.draggable = false
  img.dataset.fotosJuntosIndice = fotosJuntosIndice
  img.style.opacity = '0'
  img.addEventListener('load', () => {
    img.style.opacity = '1'
  })
  img.addEventListener('error', () => {
    imgWrap.innerHTML = '<div class="flex h-full w-full items-center justify-center text-blush/60">Esta foto todavía no está disponible ❤️</div>'
  })
  imgWrap.appendChild(img)
  img.src = fotosJuntos[fotosJuntosIndice]

  root.querySelectorAll('.fotos-juntos-dot').forEach((dot, index) => {
    const activo = index === fotosJuntosIndice
    dot.classList.toggle('bg-jade', activo)
    dot.classList.toggle('bg-white/20', !activo)
  })
  restartFotosJuntosTimer(root)
}

function restartFotosJuntosTimer(root) {
  if (fotosJuntosTimer !== null) clearInterval(fotosJuntosTimer)
  let restante = FOTOS_JUNTOS_INTERVALO_MS / 1000
  const progress = root.querySelector('[data-fotos-juntos-progress]')
  progress.textContent = `${restante}s`
  fotosJuntosTimer = setInterval(() => {
    restante -= 1
    progress.textContent = `${restante}s`
    if (restante <= 0) showFotosJuntos(fotosJuntosIndice + 1)
  }, 1000)
}

